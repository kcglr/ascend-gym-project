#!/usr/bin/env python3
"""Makes the home-screen icons and the iPhone launch pictures of the installable web app from the game art.

Run from the repository root:   python3 art/app_icons.py [--only icons|splash]

It reads assets/rank-s.webp, art/src/banner.jpg, art/src/bg.jpg and the fonts in pwa/fonts/, and writes
pwa/icons/*.png, pwa/splash/*.jpg and pwa/splash/splash.json (the list build.js turns into <link> tags).
Needs Pillow and numpy. The launch pictures also need fonttools and brotli to read the web fonts:
pip install pillow numpy fonttools brotli

The icon is the S-rank crest in front of the gate scene. Nothing here is generated by an image model:
every picture is cut and lit from art that is already in the repository, so re-running gives the same files.
"""
import io
import json
import os
import sys
import tempfile

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageEnhance, ImageFilter, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
at = lambda *p: os.path.join(ROOT, *p)

# The colours of the default theme, as in the tokens at the top of ui.css.
BG = (4, 5, 13)
GLOW = (104, 216, 255)
GLOW_MID = (56, 136, 255)
VIOLET = (84, 50, 190)
DIM = (147, 162, 204)

# Every iPhone screen from the first SE on: CSS width, CSS height, pixel ratio.
PHONES = [
    (320, 568, 2),  # SE (1st generation)
    (375, 667, 2),  # 6, 7, 8, SE (2nd and 3rd generation)
    (414, 736, 3),  # 6, 7, 8 Plus
    (375, 812, 3),  # X, XS, 11 Pro, 12 mini, 13 mini
    (414, 896, 2),  # XR, 11
    (414, 896, 3),  # XS Max, 11 Pro Max
    (390, 844, 3),  # 12, 13, 14, 16e
    (428, 926, 3),  # 12 and 13 Pro Max, 14 Plus
    (393, 852, 3),  # 14 Pro, 15, 15 Pro, 16
    (430, 932, 3),  # 14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus
    (402, 874, 3),  # 16 Pro, 17, 17 Pro
    (440, 956, 3),  # 16 Pro Max, 17 Pro Max
    (420, 912, 3),  # Air
]


# ---------- light ----------
def grid(w, h):
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    return x, y


def radial(w, h, cx, cy, r, color, power=1.0, alpha=1.0):
    """A glow: `color` at (cx, cy) fading to nothing at radius r. Positions and the radius are in pixels."""
    x, y = grid(w, h)
    a = np.clip(1 - np.hypot(x - cx, y - cy) / r, 0, 1) ** power * alpha
    layer = np.zeros((h, w, 4), np.float32)
    layer[..., :3] = color
    layer[..., 3] = a * 255
    return Image.fromarray(layer.astype(np.uint8), 'RGBA')


def rays(w, h, cx, cy, count, color, alpha, r0, r1):
    """Soft beams around (cx, cy), from radius r0 out to r1."""
    x, y = grid(w, h)
    dx, dy = x - cx, y - cy
    d = np.hypot(dx, dy)
    beam = (np.cos(np.arctan2(dy, dx) * count) * 0.5 + 0.5) ** 3
    fade = np.clip((d - r0) / (0.25 * (r1 - r0)), 0, 1) * np.clip(1 - (d - r0) / (r1 - r0), 0, 1) ** 1.4
    layer = np.zeros((h, w, 4), np.float32)
    layer[..., :3] = color
    layer[..., 3] = beam * fade * alpha * 255
    return Image.fromarray(layer.astype(np.uint8), 'RGBA')


def screen(base, layer):
    """Puts a glow layer on a picture the way light adds up."""
    b = np.asarray(base.convert('RGB'), np.float32) / 255
    l = np.asarray(layer, np.float32) / 255
    out = 1 - (1 - b) * (1 - l[..., :3] * l[..., 3:4])
    return Image.fromarray((out * 255).round().astype(np.uint8), 'RGB')


def shade(img, k):
    """Multiplies a picture by a map of 0..1."""
    return Image.fromarray((np.asarray(img, np.float32) * k[..., None]).round().astype(np.uint8), 'RGB')


def crest_layer(w, h, size, cx, cy):
    c = Image.open(at('assets', 'rank-s.webp')).convert('RGBA').resize((size, size), Image.LANCZOS)
    layer = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    layer.paste(c, (round(cx - size / 2), round(cy - size / 2)), c)
    return layer


def shadow_of(layer, blur, drop, alpha):
    a = layer.split()[3].filter(ImageFilter.GaussianBlur(blur)).point(lambda v: int(v * alpha))
    sh = Image.new('RGBA', layer.size, BG + (0,))
    sh.putalpha(a)
    return ImageChops.offset(sh, 0, drop)


# ---------- the icon ----------
def icon_master(n, crest_share):
    """The square icon at n pixels: the gate scene out of focus, a glow, and the S crest across `crest_share` of the width."""
    ban = Image.open(at('art', 'src', 'banner.jpg')).convert('RGB')
    side = ban.height
    left = min(max(398 - side // 2, 0), ban.width - side)  # the gate stands at x = 398 in the banner
    img = ban.crop((left, 0, left + side, side)).resize((n, n), Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(n / 110))
    img = ImageEnhance.Brightness(img).enhance(0.74)
    x, y = grid(n, n)
    img = shade(img, 1 - np.clip(np.hypot(x - n / 2, y - n / 2) / (n * 0.72), 0, 1) ** 2.2 * 0.82)  # darker toward the corners
    cy = n * 0.52
    img = screen(img, radial(n, n, n / 2, cy, n * 0.62, VIOLET, 1.6, 0.5))
    img = screen(img, rays(n, n, n / 2, cy, 12, GLOW, 0.3, n * 0.12, n * 0.78))
    img = screen(img, radial(n, n, n / 2, cy, n * 0.46, GLOW, 1.3, 0.8))
    crest = crest_layer(n, n, round(n * crest_share), n / 2, cy)
    img = img.convert('RGBA')
    img.alpha_composite(shadow_of(crest, n / 57, round(n / 73), 0.75))
    img.alpha_composite(crest)
    return img.convert('RGB')


def rounded(img, share=0.2237):
    """Cuts the corners off the way app icons are cut, for the places that show an icon as it is."""
    n = img.width
    mask = Image.new('L', (n * 4, n * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, n * 4 - 1, n * 4 - 1), round(n * 4 * share), fill=255)
    out = img.convert('RGBA')
    out.putalpha(mask.resize((n, n), Image.LANCZOS))
    return out


def save_png(img, name):
    path = at('pwa', 'icons', name)
    img.save(path, optimize=True)
    return os.path.getsize(path)


def make_icons():
    os.makedirs(at('pwa', 'icons'), exist_ok=True)
    full = icon_master(1024, 0.9)    # the crest fills the square: iPhone, desktop, the browser tab
    safe = icon_master(1024, 0.68)   # the crest inside the middle circle Android may cut the icon to
    tight = icon_master(1024, 1.0)   # for the tiny browser-tab icon
    sizes = {}
    sizes['apple-touch-icon.png'] = save_png(full.resize((180, 180), Image.LANCZOS), 'apple-touch-icon.png')
    for s in (192, 512):
        sizes['icon-%d.png' % s] = save_png(rounded(full.resize((s, s), Image.LANCZOS)), 'icon-%d.png' % s)
        sizes['icon-maskable-%d.png' % s] = save_png(safe.resize((s, s), Image.LANCZOS), 'icon-maskable-%d.png' % s)
    sizes['favicon-32.png'] = save_png(rounded(tight.resize((32, 32), Image.LANCZOS), 0.2), 'favicon-32.png')
    for k, v in sizes.items():
        print('  pwa/icons/%-24s %7.1f KB' % (k, v / 1024))


# ---------- the launch pictures ----------
def font(file, size, weight=None):
    """A web font from pwa/fonts as a font Pillow can draw with."""
    from fontTools.ttLib import TTFont  # only the launch pictures need it
    f = TTFont(at('pwa', 'fonts', file))
    f.flavor = None
    tmp = tempfile.NamedTemporaryFile(suffix='.ttf', delete=False)
    f.save(tmp.name)
    tmp.close()
    face = ImageFont.truetype(tmp.name, size)
    if weight is not None:
        face.set_variation_by_axes([weight])
    return face


def text_mask(w, h, text, face, cx, top, tracking=0.0):
    """A greyscale picture of one line of text, centred on cx, with extra space between the letters."""
    mask = Image.new('L', (w, h), 0)
    d = ImageDraw.Draw(mask)
    gap = tracking * face.size
    widths = [d.textlength(ch, font=face) for ch in text]
    total = sum(widths) + gap * (len(text) - 1)
    x = cx - total / 2
    for ch, cw in zip(text, widths):
        d.text((x, top), ch, font=face, fill=255)
        x += cw + gap
    return mask


def launch_picture(w, h):
    """One launch picture: the backdrop of the app, the S crest, and the name."""
    # The backdrop exactly as #bgart paints it: the scene from the top, lifted, then sunk into the page colour.
    bg = Image.open(at('art', 'src', 'bg.jpg')).convert('RGB')
    k = max(w / bg.width, h / bg.height)
    bg = bg.resize((round(bg.width * k), round(bg.height * k)), Image.LANCZOS)
    left = (bg.width - w) // 2
    img = bg.crop((left, 0, left + w, h))
    img = ImageEnhance.Color(ImageEnhance.Brightness(img).enhance(1.7)).enhance(1.2)
    img = img.filter(ImageFilter.GaussianBlur(w / 420))  # lifting the scene also lifts its grain: smooth it, which keeps the files small too
    x, y = grid(w, h)
    t = y / h
    veil = np.interp(t, [0, 0.42, 0.88, 1], [0.1, 0.55, 1, 1])  # share of the page colour over the scene
    a = np.asarray(img, np.float32)
    img = Image.fromarray((a * (1 - veil[..., None]) + np.array(BG, np.float32) * veil[..., None]).round().astype(np.uint8), 'RGB')

    cx, cy = w / 2, h * 0.4
    size = round(w * 0.56)
    img = screen(img, radial(w, h, cx, cy, w * 0.95, VIOLET, 1.7, 0.5))
    img = screen(img, rays(w, h, cx, cy, 12, GLOW, 0.22, w * 0.1, w * 0.9))
    img = screen(img, radial(w, h, cx, cy, w * 0.52, GLOW_MID, 1.4, 0.6))
    crest = crest_layer(w, h, size, cx, cy)
    img = img.convert('RGBA')
    img.alpha_composite(shadow_of(crest, w / 60, round(w / 80), 0.7))
    img.alpha_composite(crest)
    img = img.convert('RGB')

    # The name, in the style of the big words in the app: white running into the glow colour, with light behind it.
    word_size = round(w * 0.2)
    word = text_mask(w, h, 'ASCEND', font('saira-latin-700-800-italic.woff2', word_size, 800), cx, cy + size * 0.56, 0.02)
    halo = word.filter(ImageFilter.GaussianBlur(w / 28))
    glow = Image.new('RGBA', (w, h), GLOW_MID + (0,))
    glow.putalpha(halo.point(lambda v: min(255, int(v * 1.5))))
    img = screen(img, glow)
    box = word.getbbox()
    ramp = np.interp(np.arange(h), [box[1], box[1] + (box[3] - box[1]) * 0.3, box[1] + (box[3] - box[1]) * 0.8, box[3]], [0, 0, 1, 1.25])
    fill = np.zeros((h, w, 3), np.float32)
    for i in range(3):
        fill[..., i] = (255 + (GLOW[i] - 255) * np.clip(ramp, 0, 1) + (GLOW_MID[i] - GLOW[i]) * np.clip(ramp - 1, 0, 1) * 4)[:, None]
    img.paste(Image.fromarray(fill.round().astype(np.uint8), 'RGB'), (0, 0), word)

    label_size = round(w * 0.04)
    label = text_mask(w, h, 'DAILY QUEST', font('chakra-petch-latin-600.woff2', label_size), cx, box[3] + w * 0.045, 0.42)
    img.paste(Image.new('RGB', (w, h), DIM), (0, 0), label)
    return img


def make_splash():
    out = at('pwa', 'splash')
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.startswith('splash-'):
            os.remove(os.path.join(out, f))
    listing, total = [], 0
    for cw, ch, ratio in PHONES:
        w, h = cw * ratio, ch * ratio
        name = 'splash-%dx%d.jpg' % (w, h)
        launch_picture(w, h).save(os.path.join(out, name), quality=80, optimize=True, progressive=True)
        size = os.path.getsize(os.path.join(out, name))
        total += size
        listing.append({'width': cw, 'height': ch, 'ratio': ratio, 'file': name})
        print('  pwa/splash/%-24s %7.1f KB' % (name, size / 1024))
    with open(os.path.join(out, 'splash.json'), 'w') as f:
        json.dump(listing, f, indent=1)
        f.write('\n')
    print('  %d launch pictures, %.0f KB' % (len(listing), total / 1024))


if __name__ == '__main__':
    only = sys.argv[sys.argv.index('--only') + 1] if '--only' in sys.argv else None
    if only in (None, 'icons'):
        make_icons()
    if only in (None, 'splash'):
        make_splash()
